#перше завдання

print ('Hello World')

#типи данних і змінні

number = 25                #ціле число
float = 6.28               #дробове число
text = "Солдат"            #рядок
status = False             #логічне значення
numbers = [2, 4, 6, 8, 10] #список

#виведення значень іх типів

print(number, type(number))
print(float, type(float))
print(text, type(text))
print(status, type(status))
print(numbers, type(numbers))

#оператори

x = 8
y = 4

#арифметика(+, -, *, /, %, **, //)

print(x + y)   # додавання
print(x - y)   # віднімання
print(x * y)   # множення
print(x / y)   # звичайне ділення
print(x // y)  # цілочисельне ділення
print(x % y)   # залишок від ділення
print(x ** y)  # піднесення до степеня

#оператори порівняння(>, <, >=, <=, ==, !=)

print(x > y)   # більше
print(x < y)   # менше
print(x >= y)  # більше або дорівнює
print(x <= y)  # менше або дорівнює
print(x == y)  # дорівнює
print(x != y)  # не дорівнює
